#!/bin/bash
# ==============================================================================
# 🥋 Kendo OS - 静的解析＆ガバナンス監査 (Fast-Fail) 統合実行スクリプト
# ==============================================================================
# GitHub Actions CI の「🔍 静的解析＆ガバナンス監査 (Fast-Fail)」と
# 100% 完全同期した高速品質ゲートです。
#
# 【実行ステップ】:
#   [1/4] 🧹 Dartコードフォーマット & 警告の自動修復 (dart fix & dart format)
#   [2/4] 🛡️ 全31大ガバナンス法典 統合監査 (Unified Governance Runner 1/31 〜 31/31)
#   [3/4] 🔍 Flutter 静的解析 (flutter analyze: 0 issues 保証)
#   [4/4] ⚙️ Firebase Cloud Functions 自動ユニットテスト (Jest)
# ==============================================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
cd "$PROJECT_ROOT"

GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

echo ""
echo -e "${BLUE}================================================================${NC}"
echo -e "${BLUE} 🥋 Kendo OS - 静的解析＆ガバナンス監査 (Fast-Fail) 開始${NC}"
echo -e "${BLUE}================================================================${NC}"
echo ""

# ------------------------------------------------------------------------------
# [1/4] Dartコードフォーマット & 自動修復
# ------------------------------------------------------------------------------
echo -e "${YELLOW}🧹 [1/4] Dartコード・警告の全自動修復中 (dart fix & dart format)...${NC}"
dart fix --apply
dart format .
echo -e "${GREEN}✅ [1/4] Dartコードフォーマット & 自動修復 完了${NC}"
echo ""

# ------------------------------------------------------------------------------
# [2/4] 全31大ガバナンス法典 統合監査 (Python Unified Runner)
# ------------------------------------------------------------------------------
echo -e "${YELLOW}🛡️ [2/4] 全31大ガバナンス法典 統合監査を実行中 (1/31 〜 31/31)...${NC}"
python3 scripts/run_all_governance.py || {
  echo -e "${RED}❌ [2/4] ガバナンス法典監査で違反が検出されました。${NC}"
  exit 1
}
echo -e "${GREEN}✅ [2/4] 全31大ガバナンス法典監査: ALL PASS${NC}"
echo ""

# ------------------------------------------------------------------------------
# [3/4] Flutter 静的解析
# ------------------------------------------------------------------------------
echo -e "${YELLOW}🔍 [3/4] Flutter 静的解析を実行中 (Red Error/Warning保護)...${NC}"
flutter analyze --no-fatal-infos || {
  echo -e "${RED}❌ [3/4] Flutter静的解析で問題・警告が検出されました。${NC}"
  exit 1
}
echo -e "${GREEN}✅ [3/4] Flutter 静的解析: ALL PASS (問題・警告ゼロ)${NC}"
echo ""

# ------------------------------------------------------------------------------
# [4/4] Firebase Cloud Functions 自動テスト
# ------------------------------------------------------------------------------
echo -e "${YELLOW}⚙️ [4/4] Firebase Cloud Functions 自動ユニットテストを実行中 (Jest)...${NC}"
(cd functions && npm test) || {
  echo -e "${RED}❌ [4/4] Firebase Cloud Functions テストが失敗しました。${NC}"
  exit 1
}
echo -e "${GREEN}✅ [4/4] Firebase Cloud Functions 自動テスト: ALL PASS${NC}"
echo ""

echo -e "${GREEN}================================================================${NC}"
echo -e "${GREEN} 🎉 祝！静的解析＆ガバナンス監査 (Fast-Fail) 完全クリア！${NC}"
echo -e "${GREEN}    CI (GitHub Actions) と完全に一致した品質検証に合格しました。${NC}"
echo -e "${GREEN}================================================================${NC}"
echo ""
exit 0
